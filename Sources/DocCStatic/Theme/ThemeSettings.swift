import DocCStaticThemes
import Foundation

/// Represents a theme-settings.json file from swift-docc-render.
///
/// This namespace names the types that model the theme settings format used by
/// swift-docc-render, allowing themes to be shared between swift-docc and
/// swift-docc-static.  The same model, and the same validation, is used for the
/// built-in themes compiled into the binary and for custom theme files read at
/// run time.
///
/// ## Format
///
/// A theme-settings.json file has the following structure:
///
/// ```json
/// {
///   "theme": {
///     "color": {
///       "fill": { "light": "#ffffff", "dark": "#1d1d1f" },
///       "link": "#0066cc"
///     },
///     "typography": {
///       "html-font": "system-ui, sans-serif"
///     }
///   },
///   "features": {
///     "docs": { "onThisPageNavigator": { "disable": true } }
///   }
/// }
/// ```
///
/// Colour values can be either:
/// - A single string value (used for both light and dark modes)
/// - An object with `light` and `dark` keys for mode-specific values
///
/// ## Topics
///
/// ### Model Types
/// - ``Root``
/// - ``Theme``
/// - ``ColorValue``
/// - ``Value``
/// - ``FeatureFlag``
///
/// ### Built-in Themes
/// - ``BuiltInTheme``
public enum ThemeSettings {
    /// The root structure of a theme-settings.json file.
    public typealias Root = ThemeSettingsInput

    /// The `theme` section, containing colour, typography, spacing and other settings.
    public typealias Theme = ThemeInput

    /// A colour value that can be either a single string or light/dark variants.
    public typealias ColorValue = ColorValueInput

    /// A generic, possibly nested, value of the theme format.
    public typealias Value = ThemeSettingValue

    /// A feature switch in the `features` section.
    public typealias FeatureFlag = ThemeFeatureFlag
}

// MARK: - Built-in Theme Lookup

extension ThemeSettings.BuiltInTheme {
    /// The alternative names under which this theme can be selected.
    ///
    /// A built-in theme whose name starts with `docc-static-` can also be
    /// selected without that prefix; for example, `docc-static-classic` can be
    /// selected as `classic`.
    public var aliases: [String] {
        ThemeBundleLayout.aliases(forBuiltInTheme: rawValue)
    }

    /// Looks up a built-in theme by its exact name or one of its aliases.
    ///
    /// - Parameter name: The name to look up.  Matching is exact and case-sensitive.
    /// - Returns: The built-in theme, or `nil` if no theme has that name or alias.
    public static func named(_ name: String) -> Self? {
        if let theme = Self(rawValue: name) { return theme }
        return allCases.first { $0.aliases.contains(name) }
    }
}

